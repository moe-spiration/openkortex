import type { ReactNode } from "react";
import { cookies, headers } from "next/headers";
import { Geist, JetBrains_Mono } from "next/font/google";
import { PRODUCT_NAME } from "@kortex/i18n";
import { LOCALE_COOKIE, t } from "@/i18n";
import { LocaleBoot } from "@/i18n/LocaleBoot";
import { enterRequestLocale, localeOfRequest } from "@/i18n/server";
import { PREPAINT_SCRIPT } from "@/lib/shell/prefs";
import "./globals.css";

// Geist is the only text family: one variable file per subset (weights 300-500 used), swap with a size-adjusted
// fallback, so there is no layout shift. JetBrains Mono is for paths, shortcuts and code only.
const geist = Geist({ subsets: ["latin", "latin-ext"], display: "swap", variable: "--font-geist-sans" });
const jetbrainsMono = JetBrains_Mono({ subsets: ["latin"], weight: "400", display: "swap", variable: "--font-jetbrains-mono" });

// metadataBase makes the generated Open Graph image URL absolute (app/opengraph-image.png); icons,
// apple-icon and manifest.webmanifest come from app/ as well (generated by `pnpm brand`). It is this
// deployment's public address (KORTEX_WEB_URL); without it Next falls back to the request host.
const publicUrl = (() => {
  try {
    return process.env.KORTEX_WEB_URL?.trim() ? new URL(process.env.KORTEX_WEB_URL.trim()) : undefined;
  } catch {
    return undefined;
  }
})();

/** Language of this request: the cookie the client keeps, else the browser's preference. */
async function requestLocale() {
  const locale = localeOfRequest(await headers(), (await cookies()).get(LOCALE_COOKIE)?.value);
  enterRequestLocale(locale);
  return locale;
}

export async function generateMetadata() {
  await requestLocale();
  return {
    // Pages set only their own part ("Inbox"); the product name follows (Kortex or OpenKortex).
    title: { default: PRODUCT_NAME, template: `%s · ${PRODUCT_NAME}` },
    description: t("Your AI-native second brain"),
    ...(publicUrl ? { metadataBase: publicUrl } : {}),
  };
}

export default async function RootLayout({ children }: { children: ReactNode }) {
  const locale = await requestLocale();
  return (
    <html
      lang={locale}
      data-theme="dark"
      className={`${geist.variable} ${jetbrainsMono.variable}`}
      // The pre-paint script sets data-theme, data-rail and the accent before hydration.
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: PREPAINT_SCRIPT }} />
      </head>
      <body>
        <LocaleBoot locale={locale}>{children}</LocaleBoot>
      </body>
    </html>
  );
}
