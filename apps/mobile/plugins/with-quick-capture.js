/* eslint-disable @typescript-eslint/no-require-imports -- Expo loads config plugins as CommonJS */
// Quick overlay of the home screen widgets: a small translucent activity over the home screen that renders
// only the "KortexQuick" React root (src/quick/QuickCapture.tsx), not the whole app. The widgets open it with
// kortexquick://capture?kind=note|voice|task. Not exported: only this app (its widget provider) starts it.
const fs = require("node:fs");
const path = require("node:path");
const { withAndroidManifest, withAndroidStyles, withDangerousMod, AndroidConfig } = require("expo/config-plugins");

const ACTIVITY = ".QuickCaptureActivity";
const THEME = "Theme.KortexQuick";
const SCHEME = "kortexquick";

const javaSource = (pkg) => `package ${pkg};

import android.content.Intent;
import android.net.Uri;
import android.os.Bundle;

import com.facebook.react.ReactActivity;
import com.facebook.react.ReactActivityDelegate;
import com.facebook.react.defaults.DefaultReactActivityDelegate;

/** Generated by plugins/with-quick-capture.js. Renders the JS root "KortexQuick" with the kind from the link. */
public class QuickCaptureActivity extends ReactActivity {
  @Override
  protected String getMainComponentName() {
    return "KortexQuick";
  }

  @Override
  protected ReactActivityDelegate createReactActivityDelegate() {
    return new DefaultReactActivityDelegate(this, getMainComponentName()) {
      @Override
      protected Bundle getLaunchOptions() {
        Bundle props = new Bundle();
        Intent intent = getIntent();
        Uri data = intent != null ? intent.getData() : null;
        String kind = data != null ? data.getQueryParameter("kind") : null;
        props.putString("kind", kind != null ? kind : "note");
        return props;
      }
    };
  }
}
`;

function withQuickActivity(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.activity = app.activity ?? [];
    if (!app.activity.some((a) => a.$["android:name"] === ACTIVITY))
      app.activity.push({
        $: {
          "android:name": ACTIVITY,
          "android:exported": "false",
          "android:theme": `@style/${THEME}`,
          "android:excludeFromRecents": "true",
          "android:noHistory": "true",
          "android:taskAffinity": `${cfg.android?.package ?? "kortex"}.quick`,
          "android:windowSoftInputMode": "adjustResize",
          "android:configChanges": "keyboard|keyboardHidden|orientation|screenSize|screenLayout|uiMode",
        },
        "intent-filter": [
          {
            action: [{ $: { "android:name": "android.intent.action.VIEW" } }],
            category: [{ $: { "android:name": "android.intent.category.DEFAULT" } }],
            data: [{ $: { "android:scheme": SCHEME } }],
          },
        ],
      });
    return cfg;
  });
}

function withQuickTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    const styles = cfg.modResults.resources;
    styles.style = (styles.style ?? []).filter((s) => s.$.name !== THEME);
    const item = (name, value) => ({ $: { name }, _: value });
    styles.style.push({
      $: { name: THEME, parent: "Theme.AppCompat.DayNight.NoActionBar" },
      item: [
        item("android:windowIsTranslucent", "true"),
        item("android:windowBackground", "@android:color/transparent"),
        item("android:windowNoTitle", "true"),
        item("android:backgroundDimEnabled", "false"),
        item("android:windowAnimationStyle", "@android:style/Animation.Translucent"),
        item("android:statusBarColor", "@android:color/transparent"),
        item("android:navigationBarColor", "@android:color/transparent"),
      ],
    });
    return cfg;
  });
}

function withQuickClass(config) {
  return withDangerousMod(config, [
    "android",
    (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error("with-quick-capture: android.package is missing");
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app/src/main/java", ...pkg.split("."));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "QuickCaptureActivity.java"), javaSource(pkg));
      return cfg;
    },
  ]);
}

module.exports = (config) => withQuickClass(withQuickTheme(withQuickActivity(config)));
module.exports.javaSource = javaSource;
