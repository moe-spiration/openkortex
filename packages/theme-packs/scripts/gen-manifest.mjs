// media/manifest.json -> src/manifest.gen.ts (typed ids, paths, focus points). Run after the media change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const m = JSON.parse(readFileSync(join(root, "media", "manifest.json"), "utf8"));

const packIds = Object.keys(m.packs);
const topics = m.topics;
const modes = m.themes;
const lumTopics = m.accentTint.topics;
const tileTopics = topics.filter((t) => m.packs[packIds[0]].dark[t].tile);

const ref = (r) => ({ file: r.file, gzip: r.gzip, sha: r.sha });
const refs = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, ref(v)]));

const assets = {};
for (const p of packIds) {
  assets[p] = {};
  for (const mode of modes) {
    assets[p][mode] = {};
    for (const t of topics) {
      const e = m.packs[p][mode][t];
      assets[p][mode][t] = {
        ...(e.tile ? { tile: refs(e.tile) } : {}),
        full: refs(e.full),
        ...(e.lum ? { lum: refs(e.lum) } : {}),
      };
    }
  }
}

const lit = (a) => a.map((x) => JSON.stringify(x)).join(", ");
const out = `// Generated by scripts/gen-manifest.mjs from media/manifest.json. Do not edit by hand.

export const PACK_IDS = [${lit(packIds)}] as const;
export type PackId = (typeof PACK_IDS)[number];

export const MODE_IDS = [${lit(modes)}] as const;
export type ModeId = (typeof MODE_IDS)[number];

export const TOPIC_IDS = [${lit(topics)}] as const;
export type TopicId = (typeof TOPIC_IDS)[number];

/** Topics that have a tile (every topic except home). */
export const TILE_TOPICS = [${lit(tileTopics)}] as const;
export type TileTopic = (typeof TILE_TOPICS)[number];

/** Topics that follow the accent colour (luminance image). */
export const LUM_TOPICS = [${lit(lumTopics)}] as const;
export type LumTopic = (typeof LUM_TOPICS)[number];

export type TileFormat = "svg" | "avif" | "webp";
export type FullFormat = "avif" | "webp";

export interface AssetRef {
  /** Path below media/. */
  file: string;
  /** gzip size in bytes. */
  gzip: number;
  /** First 12 hex characters of the SHA-256. */
  sha: string;
}

export interface TopicAssets {
  tile?: Partial<Record<TileFormat, AssetRef>>;
  full: Record<FullFormat, AssetRef>;
  lum?: Record<FullFormat, AssetRef>;
}

export const FOCUS: Record<TopicId, { x: number; y: number }> = ${JSON.stringify(m.focus, null, 2)};

export const SPEC = ${JSON.stringify(m.spec, null, 2)} as const;

export const SURFACES = ${JSON.stringify(m.surfaces, null, 2)} as const;

export const ACCENT_TINT = ${JSON.stringify({ method: m.accentTint.method }, null, 2)} as const;

export const ASSETS: Record<PackId, Record<ModeId, Record<TopicId, TopicAssets>>> = ${JSON.stringify(assets, null, 2)};
`;
writeFileSync(join(root, "src", "manifest.gen.ts"), out);
console.log(`manifest.gen.ts: ${packIds.length} packs, ${topics.length} topics`);
