// media/manifest.json -> apps/mobile/src/theme/packAssets.gen.ts
// Android and the Expo web preview use the WebP rasters only (react-native-svg filters are unreliable, AVIF needs
// API 31). Metro needs static require() calls, so the table is generated; all seven packs are bundled.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "..", "apps", "mobile", "src", "theme", "packAssets.gen.ts");
const m = JSON.parse(readFileSync(join(root, "media", "manifest.json"), "utf8"));
const req = (r) => `require("../../../../packages/theme-packs/media/${r.file}")`;

const lines = [];
for (const pack of Object.keys(m.packs)) {
  lines.push(`  ${pack}: {`);
  for (const mode of m.themes) {
    lines.push(`    ${mode}: {`);
    for (const topic of m.topics) {
      const e = m.packs[pack][mode][topic];
      const parts = [];
      if (e.tile) parts.push(`tile: ${req(e.tile.webp)}`);
      parts.push(`full: ${req(e.full.webp)}`);
      if (e.lum) parts.push(`lum: ${req(e.lum.webp)}`);
      lines.push(`      ${topic}: { ${parts.join(", ")} },`);
    }
    lines.push("    },");
  }
  lines.push("  },");
}

const text = `// Generated by packages/theme-packs/scripts/gen-android.mjs from media/manifest.json. Do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports -- Metro resolves bundled images through require() */
import type { ImageSourcePropType } from "react-native";
import type { ModeId, PackId, TopicId } from "@kortex/theme-packs";

export interface PackTopicImages {
  /** 800x470 tile (every topic except home). */
  tile?: ImageSourcePropType;
  /** 320x180 baked fullscreen. */
  full: ImageSourcePropType;
  /** Greyscale image for the accent tint (home and review). */
  lum?: ImageSourcePropType;
}

export const PACK_IMAGES: Record<PackId, Record<ModeId, Record<TopicId, PackTopicImages>>> = {
${lines.join("\n")}
};
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, text);
console.log(`packAssets.gen.ts: ${(text.match(/require\(/g) ?? []).length} images`);
